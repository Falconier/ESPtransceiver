"""Writes beacon/olivia_symbols.h: the beacon's ID as Olivia symbols, encoded by the station's own olivia.py.

  python beacon/gen_olivia.py [MODE]          (MODE 16/500 by default; beacon/build.sh runs this before every build)

The text and the tone (the band's centre above the dial) come from BEACON_TEXT and BEACON_TONE_HZ in beacon.c, so the call sign
is set in one place. The symbols (Gray-coded tone numbers, 4 bits each, 8 to a word) go into instruction RAM: the image's data
region has no room left.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import olivia                                                    # noqa: E402

mode_name = sys.argv[1] if len(sys.argv) > 1 else "16/500"
src = (ROOT / "beacon" / "beacon.c").read_text(encoding="utf-8")
text = re.search(r'#define BEACON_TEXT "([^"]*)"', src).group(1)
tone = int(re.search(r"#define BEACON_TONE_HZ (\d+)", src).group(1))

m = olivia.Mode(mode_name, center=float(tone))
if m.tones > 16:
    sys.exit("only modes with up to 16 tones fit 4 bits per symbol")
message = text + " "                          # a space after the ID keeps repeated IDs apart on the receiving screen
syms = m.symbols(message)
words = [sum(s << (4 * j) for j, s in enumerate(syms[i:i + 8])) for i in range(0, len(syms), 8)]
hz16 = lambda f: int(round(f * 16))            # noqa: E731 - 1/16 Hz: Olivia's tone plan is exact in these units
assert all(abs(f * 16 - hz16(f)) < 1e-9 for f in (m.first, m.spacing)), "the tone plan is not a whole number of 1/16 Hz"

rows = ",\n".join("    " + ", ".join(f"0x{w:08X}u" for w in words[i:i + 6]) for i in range(0, len(words), 6))
out = f"""/* Generated by beacon/gen_olivia.py from BEACON_TEXT and BEACON_TONE_HZ in beacon.c; do not edit. */
#pragma once
#include <stdint.h>

#define OLIVIA_NAME "Olivia {m.name}"
#define OLIVIA_TEXT {message!r}
#define OLIVIA_SYMBOLS {len(syms)}
#define OLIVIA_SYMBOL_TICKS {int(round(m.symbol_s * 8000))} /* records per symbol at 8000 per second */
#define OLIVIA_CENTER_HZ16 {hz16(m.center)}   /* the lead tone, 1/16 Hz above the dial */
#define OLIVIA_FIRST_HZ16 {hz16(m.first)}    /* tone 0 */
#define OLIVIA_SPACING_HZ16 {hz16(m.spacing)}
#define OLIVIA_TONE_HZ {tone}               /* checked against BEACON_TONE_HZ when compiled */

/* Tone numbers, 4 bits each, the first symbol in the lowest bits; in instruction RAM (32-bit reads only). */
static const uint32_t __attribute__((section(".iram1.olivia_symbols"), aligned(4))) olivia_words[{len(words)}] = {{
{rows},
}};
"""
(ROOT / "beacon" / "olivia_symbols.h").write_text(out.replace("'", '"'), encoding="utf-8", newline="\n")
print(f"beacon/olivia_symbols.h: {m.name}, {message!r}, {len(syms)} symbols ({len(syms) * m.symbol_s:.1f} s)")
